#!/usr/bin/env node
// Generates src/modules/auth/data/breached-passwords.ts from the SecLists word list next to it
// (src/modules/auth/data/10k-most-common.txt, see NOTICE.md there). The list ships as TypeScript so it is
// compiled into dist like any other source (no asset copying in `tsc --watch` development).
//
//   node scripts/generate-breached-passwords.mjs
//
// A test (breached-passwords.spec.ts) fails when the two files disagree.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'modules', 'auth', 'data');
const words = [
  ...new Set(
    readFileSync(join(dir, '10k-most-common.txt'), 'utf8')
      .split(/\r?\n/)
      .filter((line) => line.length > 0),
  ),
];

const body = words.map((w) => `  ${JSON.stringify(w)},`).join('\n');
writeFileSync(
  join(dir, 'breached-passwords.ts'),
  `// GENERATED by scripts/generate-breached-passwords.mjs from 10k-most-common.txt. Do not edit.
// Source: SecLists (MIT), commit 913b327317496d062bcc7cace524aaad8a693be2, see NOTICE.md.
export const BREACHED_PASSWORDS: readonly string[] = [
${body}
];
`,
);
console.log(`${words.length} passwords written`);
